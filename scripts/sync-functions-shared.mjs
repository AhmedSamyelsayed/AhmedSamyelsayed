#!/usr/bin/env node
// Copies shared, dependency-light modules into the Edge Functions tree so
// Supabase bundles them without reaching outside supabase/functions.
//   node scripts/sync-functions-shared.mjs          write copies
//   node scripts/sync-functions-shared.mjs --check  fail if copies are stale (CI)
import { mkdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const FILES = ['job-analysis.ts'];
const HEADER =
  '// GENERATED by scripts/sync-functions-shared.mjs from packages/shared/src. Do not edit.\n';
const check = process.argv.includes('--check');
let stale = 0;

for (const file of FILES) {
  const source = HEADER + readFileSync(join(root, 'packages/shared/src', file), 'utf8');
  const target = join(root, 'supabase/functions/_shared/generated', file);
  const current = existsSync(target) ? readFileSync(target, 'utf8') : null;
  if (current === source) continue;
  if (check) {
    console.error(`✗ ${target} is out of date. Run: node scripts/sync-functions-shared.mjs`);
    stale++;
  } else {
    mkdirSync(dirname(target), { recursive: true });
    writeFileSync(target, source);
    console.log(`synced ${file}`);
  }
}
if (stale) process.exit(1);
if (check) console.log('✓ Edge Function shared copies are up to date');
